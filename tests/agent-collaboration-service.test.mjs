import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { createAgentCollaborationService } = require('../server/agent-collaboration-service.js');
const { createFileWorkflowStore } = require('../server/workflow-store.js');
const { createRoofRiskRepository } = require('../server/roof-risk-repository.js');
const artifact = JSON.parse(await readFile(new URL('../data/roof-risk-dataset.json', import.meta.url), 'utf8'));
const actors = Object.fromEntries(['enterprise', 'regulator', 'expert', 'viewer', 'super_admin'].map(role => [role, { username: role, role, displayName: role }]));
const recordId = 'REC-202511101149-02909';
const disposal = { measures: '复测支护', workOrder: 'WO-1', responsiblePerson: '现场负责人', completedAt: '2026-10-12T10:00:00Z', photos: [{ name: 'photo.jpg', size: 42 }], monitoring_trend: 'stable', execution_status: 'completed' };
const errorStatus = status => e => e.statusCode === status;
async function fixture(t) {
  const directory = await mkdtemp(path.join(tmpdir(), 'mine-collaboration-'));
  t.after(() => rm(directory, { recursive: true, force: true }));
  let adviceCalls = 0;
  const adviceInputs = [];
  const adviceService = { configured: false, async generateWorkflowAdvice(input) { adviceCalls++; adviceInputs.push(input); return { source: 'local-rule', summary: '候选方案', recommendations: ['复测支护'], evidence_ids: input.feature_evidence.map(e => e.id) }; } };
  const make = () => createAgentCollaborationService({ repository: createRoofRiskRepository(artifact), store: createFileWorkflowStore({ directory }), adviceService });
  const service = make();
  const start = (commandId = 'start', extra = {}) => service.start({ recordId, actor: actors.enterprise, commandId, ...extra });
  const act = (run, type, payload = {}, role = 'enterprise', commandId = `${type}-${run.revision}`) => service.act({ runId: run.workflow_run_id, type, payload, actor: actors[role], expectedRevision: run.revision, commandId });
  return { service, start, act, make, adviceInputs, calls: () => adviceCalls };
}
test('saved start is idempotent, traceable, restartable and read-only roles cannot sign', async t => {
  const f = await fixture(t), run = await f.start();
  assert.deepEqual(await f.start(), run);
  assert.equal(f.calls(), 1);
  assert.equal(f.adviceInputs[0].feature_evidence.length, 7);
  assert.equal(run.demo_state.sourceRecordId, recordId);
  assert.equal(run.demo_state.eventId, run.workflow_run_id);
  assert.equal(run.demo_state.status, 'alert_triggered');
  assert.equal(run.phase, run.current_phase);
  const status = await f.service.status();
  assert.equal(status.storage_provider, 'file');
  assert.equal(status.durable, true);
  assert.equal(status.advice_configured, false);
  assert.equal(run.nodes[5].output.return_decision.action, 'wait_for_feedback');
  for (const role of ['regulator', 'expert', 'viewer', 'super_admin']) await assert.rejects(f.service.start({ recordId, actor: actors[role], commandId: 'forbidden' }), errorStatus(403));
  for (const role of ['enterprise', 'expert', 'viewer', 'super_admin']) await assert.rejects(f.act(run, 'APPROVE', { opinion: 'checked' }, role), errorStatus(403));
  await assert.rejects(f.service.get('WF-00000000-0000-4000-8000-999999999999'), errorStatus(404));
  assert.deepEqual(await f.make().get(run.workflow_run_id), run);
  assert.equal((await f.service.list({ recordId }))[0].workflow_run_id, run.workflow_run_id);
});
test('actions use saved revision, deduplicate before phase validation and preserve evidence', async t => {
  const f = await fixture(t), run = await f.start();
  const agreed = await f.act(run, 'ACKNOWLEDGE', {}, 'enterprise', 'ack');
  assert.equal(agreed.demo_state.status, 'disposal_in_progress');
  assert.equal(agreed.events.at(-1).actor.role, 'enterprise');
  assert.equal(agreed.events.at(-1).command_id, 'ack');
  assert.deepEqual(await f.act(run, 'ACKNOWLEDGE', {}, 'enterprise', 'ack'), agreed);
  await assert.rejects(f.act(run, 'ACKNOWLEDGE', {}, 'enterprise', 'new'), errorStatus(409));
  await assert.rejects(f.act(run, 'ACKNOWLEDGE', {}, 'viewer', 'ack'), errorStatus(403));
  await assert.rejects(f.service.act({ runId: run.workflow_run_id, type: 'ACKNOWLEDGE', payload: {}, actor: { username: 'other-enterprise', role: 'enterprise' }, expectedRevision: 0, commandId: 'ack' }), errorStatus(409));
  let submitted = await f.act(agreed, 'SUBMIT_DISPOSAL', disposal);
  assert.equal(submitted.demo_state.disposal.photos[0].storage_source, 'browser-local');
  let rejected = await f.act(submitted, 'REJECT', { opinion: '需补充', deadline: '2026-10-15' }, 'regulator');
  assert.equal(rejected.demo_state.status, 'changes_requested');
  assert.equal(rejected.nodes[5].output.return_decision.action, 'return_to_decision');
  submitted = await f.act(rejected, 'SUBMIT_DISPOSAL', disposal);
  let approved = await f.act(submitted, 'APPROVE', { opinion: 'checked' }, 'regulator');
  assert.equal(approved.demo_state.status, 'verified');
  await assert.rejects(f.act(approved, 'REPROCESS', { confirmed: true }), errorStatus(400));
  const archived = await f.act(approved, 'ARCHIVE', { conclusion: '复盘完成' }, 'expert');
  assert.equal(archived.demo_state.status, 'archived');
  assert.equal(archived.feedback.filter(e => e.type === 'SUBMIT_DISPOSAL').length, 2);
  await f.start('unreviewed');
  assert.equal(f.adviceInputs.at(-1).reviewed_memory.length, 0);
  const reviewed = await f.act(archived, 'APPROVE_MEMORY', { reviewed_conclusion: '人工审阅：处置过程可参考' }, 'expert');
  assert.equal(reviewed.case_memory[0].reviewed, true);
  assert.equal(reviewed.demo_state.revision, reviewed.revision);
  await f.start('next');
  assert.equal(f.adviceInputs.at(-1).reviewed_memory.length, 1);
});
test('resource and worsening branches require confirmation and bound new plan versions', async t => {
  const f = await fixture(t);
  let run = await f.start('short', { resourceSnapshot: { personnel_available: 0 } });
  assert.equal(run.next_action, 'return_to_resource');
  assert.equal(run.nodes[5].output.return_decision.action, 'return_to_resource');
  await assert.rejects(f.act(run, 'ACKNOWLEDGE'), errorStatus(400));
  run = await f.act(run, 'UPDATE_RESOURCES', { resource_snapshot: { personnel_available: 6 } });
  assert.equal(run.nodes[3].output.feasibility, 'feasible');
  await assert.rejects(f.act(run, 'REPROCESS'), errorStatus(400));
  run = await f.act(run, 'REPROCESS', { confirmed: true });
  const id = run.workflow_run_id, originalRisk = run.algorithm.predicted_class;
  run = await f.act(run, 'ACKNOWLEDGE');
  run = await f.act(run, 'SUBMIT_DISPOSAL', { ...disposal, monitoring_trend: 'worsened' });
  assert.equal(run.nodes[5].output.return_decision.action, 'return_to_perception');
  run = await f.act(run, 'REPROCESS', { confirmed: true });
  assert.equal(run.demo_state.status, 'alert_triggered');
  assert.equal(run.plan_versions.at(-1).reprocess_from, 'return_to_perception');
  assert.equal(run.plan_versions.at(-1).monitoring_evidence, 'original_csv_record');
  assert.equal(run.demo_state.alertSeenRevision, null);
  assert.ok(run.demo_state.timeline.some(e => e.type === 'SUBMIT_DISPOSAL'));
  assert.equal(run.feedback.at(-1).source, 'human-input');
  while (run.plan_versions.length < 5) run = await f.act(run, 'REPROCESS', { confirmed: true });
  await assert.rejects(f.act(run, 'REPROCESS', { confirmed: true }), errorStatus(400));
  assert.equal(run.workflow_run_id, id);
  assert.equal(run.algorithm.predicted_class, originalRisk);
  const before = f.calls();
  await assert.rejects(f.act(run, 'RESET'), errorStatus(400));
  await assert.rejects(f.act(run, 'APPROVE_MEMORY', { reviewed_conclusion: 'not archived' }, 'expert'), errorStatus(400));
  assert.equal(f.calls(), before);
});
