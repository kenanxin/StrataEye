test('confirmed reprocess saves new manual feedback before choosing a return path', async t => {
  const f = await fixture(t);
  let run = await f.start('manual-feedback');
  const before = f.calls();
  for (const feedback of [{ monitoring_trend: 'fabricated' }, { execution_status: 'invented' }, { reason: 42 }, { reason: 'x'.repeat(2001) }, { risk: 'red' }, { recordId: 'fake' }, null]) await assert.rejects(f.act(run, 'REPROCESS', { confirmed: true, feedback }), errorStatus(400));
  assert.equal(f.calls(), before);
  run = await f.act(run, 'REPROCESS', { confirmed: true, feedback: { monitoring_trend: 'worsened', reason: '现场人员报告趋势待复核' } });
  assert.equal(run.feedback.at(-1).source, 'human-input');
  assert.equal(run.feedback.at(-1).reason, '现场人员报告趋势待复核');
  assert.equal(run.revision, 1);
  assert.equal(run.events.length, 2);
  assert.equal(run.plan_versions.length, 2);
  assert.equal((await f.make().get(run.workflow_run_id)).feedback.length, 1);
  assert.ok(!JSON.stringify(f.adviceInputs.at(-1)).includes('现场人员报告趋势待复核'));
  assert.equal(run.plan_versions.at(-1).reprocess_from, 'return_to_perception');
  assert.equal(run.algorithm.record_id, recordId);
  assert.equal(run.demo_state.sourceRecordId, recordId);
});
